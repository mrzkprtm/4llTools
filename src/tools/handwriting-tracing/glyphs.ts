import type { Pt } from './logic'

/**
 * Letters and digits as strokes in stroke order. Each glyph sits in a 60 × 100
 * box: capitals and ascenders start at y = 10, the x-height (midline) is at
 * y = 45, the baseline at y = 80 and descenders reach y = 98.
 */
export const BOX = { w: 60, top: 10, mid: 45, base: 80, desc: 98 }

const L = (...pts: Pt[]): Pt[] => pts

/** Points on an ellipse from angle a0 to a1 in degrees (0 = right, positive = clockwise on screen). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number): Pt[] {
  const steps = Math.max(6, Math.ceil(Math.abs(a1 - a0) / 10))
  return Array.from({ length: steps + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180
    return [Math.round((cx + rx * Math.cos(a)) * 10) / 10, Math.round((cy + ry * Math.sin(a)) * 10) / 10] as Pt
  })
}

/** One stroke made of several pieces drawn without lifting the pen. */
const join = (...parts: Pt[][]): Pt[] => parts.flat()

